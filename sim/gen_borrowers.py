"""Write sim/src/Borrowers.sol: the borrowers of each Morpho market, from Morpho's API.

Usage: python sim/gen_borrowers.py
Borrower lists are a snapshot; regenerate them when you re-pin the fork block.
"""
import json
import urllib.request
from pathlib import Path

MARKETS = {
    "sUSDe_USDC": "0x5613b170ded221c588b6e9637b910f49e5508680ceede207f44aa72e5c46cb05",
    "reUSD_USDC": "0x1e9d614631a7df0ec07fb05b2c8cb2491575fd1a63a33bf187a6afb295a4fc64",
    "reUSD_USDT": "0x6acd18854e43f93f5a90446004c35c72a68af1ad99f08cb247782ce6457914ca",
    "sUSDS_USDC": "0x22fe4c688161863c73571a2b8db65cc11a4a6bceee4f0dea4aa83e4b784f1bd9",
    "sUSDS_USDT": "0x0367161b7cb23dfd03747dd3815d1c445b0437b648a6d50346249c6e7b92ff1b",
    "sUSDS_USDS": "0x9a8dab6de1059e6dc66c34b358764b70effb289e514e237f3161ffb09eaaf24f",
}


def borrowers(market_id):
    out, skip = [], 0
    while True:
        q = ('{ marketPositions(first: 100, skip: %d, where: {marketUniqueKey_in: ["%s"], borrowShares_gte: 1}) '
             '{ items { user { address } } } }') % (skip, market_id)
        req = urllib.request.Request("https://blue-api.morpho.org/graphql", json.dumps({"query": q}).encode(),
                                     {"Content-Type": "application/json", "User-Agent": "defi-risk/0.1"})
        items = json.load(urllib.request.urlopen(req, timeout=60))["data"]["marketPositions"]["items"]
        out += [i["user"]["address"] for i in items]
        if len(items) < 100:
            return out
        skip += 100


def main():
    funcs = []
    for name, mid in MARKETS.items():
        addrs = borrowers(mid)
        body = "\n".join(f"        a[{i}] = {a};" for i, a in enumerate(addrs))
        funcs.append(f"    function {name}() internal pure returns (address[] memory a) {{\n"
                     f"        a = new address[]({len(addrs)});\n{body}\n    }}")
        print(name, len(addrs), "borrowers")
    src = ("// SPDX-License-Identifier: MIT\npragma solidity ^0.8.26;\n\n"
           "/// Borrowers per Morpho market at generation time (Morpho API). Generated by gen_borrowers.py.\n"
           "library Borrowers {\n" + "\n\n".join(funcs) + "\n}\n")
    Path(__file__).with_name("src").joinpath("Borrowers.sol").write_text(src)


if __name__ == "__main__":
    main()
